function JuftToq(arr) {
  let Juft = [];
  let Toq = [];
  for (let i = 0; i < arr.length; i++) {
    if (arr[i] % 2 === 0) {
      Juft.push(arr[i]);
    } else {
      Toq.push(arr[i]);
    }
  }
  return [Juft, Toq];
}

